import assert from "node:assert/strict";
import test from "node:test";
import {
	parseSuggestionPayload,
	SUGGESTION_EXPIRY_DAYS,
	suggestionExpiresAt,
	suggestionTitle,
} from "../src/lib/agent/auto-read/suggestion-utils.ts";

const invite = {
	uid: "abc@calendar.test",
	sequence: 1,
	method: "REQUEST",
	organizer: "boss@corp.test",
	start: "2026-10-20T14:00:00.000Z",
	end: "2026-10-20T15:00:00.000Z",
	tz: "Europe/Amsterdam",
	summary: "Planning",
	location: null,
	repeats: false,
	conflicts: [],
	proposals: [],
	organizerMatchesSender: true,
	authPassed: false,
};

test("suggestions expire after 14 days", () => {
	assert.equal(SUGGESTION_EXPIRY_DAYS, 14);
	assert.equal(suggestionExpiresAt(new Date("2026-10-01T10:00:00Z")).toISOString(), "2026-10-15T10:00:00.000Z");
});

test("titles are generated by code and capped at 200 characters", () => {
	assert.equal(suggestionTitle({ kind: "reply", payload: { urgency: "low" } }), "Reply drafted");
	assert.equal(suggestionTitle({ kind: "phishing", payload: { reasons: ["x"] } }), "This message looks like phishing");
	assert.equal(suggestionTitle({ kind: "summary", payload: { text: "t" } }), "Summary");
	assert.equal(suggestionTitle({ kind: "receipt", payload: {} }), "Receipt or invoice");
	assert.equal(suggestionTitle({ kind: "calendar_invite", payload: invite }), "Invitation: Planning");
	assert.equal(
		suggestionTitle({ kind: "calendar_invite", payload: { ...invite, summary: " " } }),
		"Invitation: Untitled event",
	);
	assert.equal(
		suggestionTitle({ kind: "calendar_invite", payload: { ...invite, method: "CANCEL" } }),
		"Cancelled: Planning",
	);
	const conflict = { eventId: "e1", title: "Team sync", start: invite.start, end: invite.end };
	assert.equal(
		suggestionTitle({ kind: "calendar_invite", payload: { ...invite, conflicts: [conflict] } }),
		"Planning conflicts with Team sync",
	);
	assert.equal(
		suggestionTitle({ kind: "calendar_invite", payload: { ...invite, conflicts: [{ ...conflict, title: "" }] } }),
		"Planning conflicts with another event",
	);
	assert.equal(
		suggestionTitle({ kind: "task", payload: { title: "Pay invoice", dueAt: "2026-11-03T00:00:00.000Z" } }),
		"Due 2026-11-03: Pay invoice",
	);
	assert.equal(suggestionTitle({ kind: "task", payload: { title: "Call back" } }), "To do: Call back");
	const long = suggestionTitle({ kind: "calendar_invite", payload: { ...invite, summary: "x".repeat(400) } });
	assert.equal(Array.from(long).length, 200);
	assert.ok(long.endsWith("…"));
});

test("payloads are validated per kind", () => {
	assert.deepEqual(parseSuggestionPayload("reply", { urgency: "high", extra: 1 }), { urgency: "high" });
	assert.equal(parseSuggestionPayload("reply", { urgency: "urgent" }), null);
	assert.deepEqual(parseSuggestionPayload("summary", { text: "Short" }), { text: "Short" });
	assert.equal(parseSuggestionPayload("summary", { text: "x".repeat(281) }), null);
	const emoji = "😀".repeat(280);
	assert.deepEqual(parseSuggestionPayload("summary", { text: emoji }), { text: emoji }, "lengths count characters");
	assert.equal(parseSuggestionPayload("summary", { text: "😀".repeat(281) }), null);
	assert.deepEqual(parseSuggestionPayload("task", { title: "📅".repeat(120) }), { title: "📅".repeat(120) });
	assert.equal(parseSuggestionPayload("task", { title: "📅".repeat(121) }), null);
	assert.equal(parseSuggestionPayload("phishing", { reasons: [] }), null);
	assert.deepEqual(parseSuggestionPayload("phishing", { reasons: ["suspicious_verdict"] }), {
		reasons: ["suspicious_verdict"],
	});
	assert.deepEqual(parseSuggestionPayload("calendar_invite", invite), invite);
	assert.equal(parseSuggestionPayload("calendar_invite", { ...invite, start: "tomorrow" }), null);
	assert.equal(parseSuggestionPayload("calendar_invite", { ...invite, method: "PUBLISH" }), null);
	assert.deepEqual(parseSuggestionPayload("task", { title: "Pay" }), { title: "Pay" });
	assert.equal(parseSuggestionPayload("task", { title: "" }), null);
	assert.deepEqual(parseSuggestionPayload("receipt", { forwardTo: "x@evil.test" }), {});
	assert.deepEqual(parseSuggestionPayload("follow_up", {}), {});
	assert.equal(parseSuggestionPayload("label", null), null);
});
