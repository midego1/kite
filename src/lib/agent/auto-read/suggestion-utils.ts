import { z } from "zod";
import type {
	SuggestionContent,
	SuggestionCount,
	SuggestionKind,
	SuggestionPayloads,
	TaskSuggestionPayload,
} from "./suggestion-types";

export const SUGGESTION_EXPIRY_DAYS = 14;
const TITLE_MAX_CHARS = 200;
const BADGE_PRIORITY: readonly SuggestionKind[] = ["phishing", "calendar_invite", "reply", "task", "receipt"];

const isoDate = z.iso.datetime({ offset: true });
const empty = z.object({});

const calendarInviteSchema = z.object({
	uid: z.string().min(1).max(1_000),
	sequence: z.number().int().min(0),
	method: z.enum(["REQUEST", "CANCEL"]),
	organizer: z.string().max(320).nullable(),
	start: isoDate,
	end: isoDate,
	tz: z.string().max(100).nullable(),
	summary: z.string().max(500),
	location: z.string().max(500).nullable(),
	repeats: z.boolean(),
	conflicts: z
		.array(z.object({ eventId: z.string(), title: z.string().max(500), start: isoDate, end: isoDate }))
		.max(20),
	proposals: z.array(z.object({ start: isoDate, end: isoDate })).max(5),
	organizerMatchesSender: z.boolean(),
	authPassed: z.boolean(),
});

const PAYLOAD_SCHEMAS: { [K in SuggestionKind]: z.ZodType<SuggestionPayloads[K]> } = {
	calendar_invite: calendarInviteSchema,
	reply: z.object({ urgency: z.enum(["none", "low", "high"]) }),
	summary: z.object({ text: z.string().min(1).max(280) }),
	phishing: z.object({ reasons: z.array(z.string().min(1).max(60)).min(1).max(20) }),
	task: z.object({ title: z.string().min(1).max(120), dueAt: isoDate.optional() }),
	receipt: empty as z.ZodType<Record<string, never>>,
	label: empty as z.ZodType<Record<string, never>>,
	unsubscribe: empty as z.ZodType<Record<string, never>>,
	follow_up: empty as z.ZodType<Record<string, never>>,
};

/** Validates a stored or planned payload against its kind's schema; null when it does not match. */
export function parseSuggestionPayload<K extends SuggestionKind>(
	kind: K,
	value: unknown,
): SuggestionPayloads[K] | null {
	const parsed = PAYLOAD_SCHEMAS[kind].safeParse(value);
	return parsed.success ? parsed.data : null;
}

function cap(title: string): string {
	const chars = Array.from(title.replace(/\s+/g, " ").trim());
	return chars.length > TITLE_MAX_CHARS ? `${chars.slice(0, TITLE_MAX_CHARS - 1).join("")}…` : chars.join("");
}

function inviteTitle(payload: SuggestionPayloads["calendar_invite"]): string {
	const name = payload.summary.trim() || "Untitled event";
	if (payload.method === "CANCEL") return `Cancelled: ${name}`;
	const [conflict] = payload.conflicts;
	return conflict ? `${name} conflicts with ${conflict.title.trim() || "another event"}` : `Invitation: ${name}`;
}

function taskTitle(payload: TaskSuggestionPayload): string {
	return payload.dueAt ? `Due ${payload.dueAt.slice(0, 10)}: ${payload.title}` : `To do: ${payload.title}`;
}

const STATIC_TITLES: Record<SuggestionKind, string> = {
	calendar_invite: "Invitation",
	reply: "Reply drafted",
	summary: "Summary",
	phishing: "This message looks like phishing",
	task: "To do",
	receipt: "Receipt or invoice",
	label: "Suggested folder",
	unsubscribe: "Unsubscribe?",
	follow_up: "No reply yet",
};

/** The card title, generated by code from the payload (at most 200 characters). */
export function suggestionTitle(suggestion: SuggestionContent): string {
	if (suggestion.kind === "calendar_invite") return cap(inviteTitle(suggestion.payload));
	if (suggestion.kind === "task") return cap(taskTitle(suggestion.payload));
	return STATIC_TITLES[suggestion.kind];
}

export function suggestionExpiresAt(createdAt: Date): Date {
	return new Date(createdAt.getTime() + SUGGESTION_EXPIRY_DAYS * 24 * 60 * 60_000);
}

/** The inbox chip: the highest-priority open kind, plus how many other chip-worthy suggestions exist. */
export function pickSuggestionBadge(counts: SuggestionCount[]): { kind: SuggestionKind; more: number } | null {
	const total = (kind: SuggestionKind) =>
		counts.filter((entry) => entry.kind === kind).reduce((sum, entry) => sum + Math.max(0, entry.count), 0);
	const kind = BADGE_PRIORITY.find((candidate) => total(candidate) > 0);
	if (!kind) return null;
	const all = BADGE_PRIORITY.reduce((sum, candidate) => sum + total(candidate), 0);
	return { kind, more: all - 1 };
}
